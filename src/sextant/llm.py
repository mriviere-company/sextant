"""Chat completions returning JSON, for the evaluation tooling.

Phase 1 uses an LLM to draft evaluation questions and to judge which pooled
sections answer them; phase 4 will reuse it for the LLM judge. Three
properties matter more than convenience:

- **Reproducible.** Every response is cached on disk, keyed by the full
  request (model, prompts, sampling parameters). Re-running a pipeline
  replays the cache instead of sampling again, so the committed candidates can
  be regenerated byte for byte without spending anything.
- **Bounded.** A token budget stops a run that loops or misbehaves before it
  costs real money (`BudgetExceededError`).
- **No secret in code.** The key is read from `DEEPSEEK_API_KEY`; nothing
  else is accepted.

DeepSeek speaks the OpenAI protocol, so the OpenAI SDK is the client. Its v4
models reason before answering by default and count that reasoning against
`max_tokens`, which can leave a short JSON answer empty: thinking is disabled
explicitly on every call.
"""

from __future__ import annotations

import hashlib
import json
import os
import threading
from pathlib import Path
from typing import Any, Literal, Protocol

from pydantic import BaseModel, ConfigDict

DEEPSEEK_BASE_URL = "https://api.deepseek.com/v1"
# DeepSeek-V4.1-Flash; its former name "deepseek-v4-flash" is retired (still billed as flash).
FAST_MODEL = "deepseek-flash"
STRONG_MODEL = "deepseek-v4-pro"
DEFAULT_TOKEN_BUDGET = 6_000_000

Role = Literal["draft", "relevance_judge", "reassessment", "strict_check", "answer_judge"]

# The model of each kind of call (eval/LLM_MODELS.md). Drafts are flash: a person reviews
# every drafted question and answer. Judges feed reference labels that nobody re-checks, so
# their model was chosen by measurement against pro (eval/results/judge_models.json): flash
# agrees on relevance (kappa 0.81), not on the two claim checks (0.54 and 0.60).
MODELS: dict[Role, str] = {
    "draft": FAST_MODEL,
    "relevance_judge": FAST_MODEL,
    "reassessment": STRONG_MODEL,
    "strict_check": STRONG_MODEL,
    "answer_judge": STRONG_MODEL,
}
FORCE_MODEL_ENV = "SEXTANT_EVAL_MODEL"


def model_for(role: Role) -> str:
    """Return the model of a role, or the one `SEXTANT_EVAL_MODEL` forces on every role.

    Version 1 of the evaluation set and the v2 re-assessment ran with `deepseek-v4-pro`
    everywhere; forcing it replays them from the response cache.
    """
    return os.environ.get(FORCE_MODEL_ENV) or MODELS[role]


class LlmError(RuntimeError):
    """The model returned something unusable (empty, truncated, not JSON)."""


class BudgetExceededError(RuntimeError):
    """The run spent its token budget."""


class Request(BaseModel):
    """Everything that determines a response, hence the cache key."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    model: str
    system: str
    user: str
    max_tokens: int
    temperature: float

    def key(self) -> str:
        """Stable hash of the request."""
        payload = json.dumps(self.model_dump(), sort_keys=True, ensure_ascii=False)
        return hashlib.sha256(payload.encode("utf-8")).hexdigest()


class Usage(BaseModel):
    """Token counts of a run; cached replays cost nothing and are counted apart."""

    calls: int = 0
    cached_calls: int = 0
    prompt_tokens: int = 0
    completion_tokens: int = 0
    prompt_cache_hit_tokens: int = 0

    @property
    def total_tokens(self) -> int:
        """Tokens actually billed (prompt + completion) by this run."""
        return self.prompt_tokens + self.completion_tokens


class JsonLlm(Protocol):
    """A chat model that answers with one JSON object."""

    def complete_json(self, request: Request) -> dict[str, Any]:
        """Return the parsed JSON object answering `request`."""
        ...


class DiskCache:
    """One JSON file per request hash; atomic writes, safe across threads."""

    def __init__(self, directory: Path) -> None:
        self.directory = directory

    def _path(self, request: Request) -> Path:
        key = request.key()
        return self.directory / key[:2] / f"{key}.json"

    def get(self, request: Request) -> str | None:
        """Return the cached raw response, if any."""
        path = self._path(request)
        if not path.exists():
            return None
        record = json.loads(path.read_text(encoding="utf-8"))
        content = record.get("content")
        return content if isinstance(content, str) else None

    def put(self, request: Request, content: str, usage: dict[str, int]) -> None:
        """Store a raw response with its request, for auditing."""
        path = self._path(request)
        path.parent.mkdir(parents=True, exist_ok=True)
        record = {"request": request.model_dump(), "content": content, "usage": usage}
        tmp = path.with_suffix(f".{threading.get_ident()}.tmp")
        tmp.write_text(json.dumps(record, ensure_ascii=False, indent=1), encoding="utf-8")
        tmp.replace(path)


def parse_json_object(content: str) -> dict[str, Any]:
    """Parse a model answer that must be one JSON object (tolerates a ```json fence)."""
    text = content.strip()
    if text.startswith("```"):
        text = text.strip("`")
        text = text.removeprefix("json").strip()
    try:
        value = json.loads(text)
    except json.JSONDecodeError as error:
        raise LlmError(f"answer is not JSON: {content[:200]!r}") from error
    if not isinstance(value, dict):
        raise LlmError("answer is JSON but not an object")
    return value


class DeepSeekJsonLlm:
    """DeepSeek through the OpenAI SDK, with disk cache and token budget."""

    def __init__(
        self,
        cache: DiskCache,
        budget: int = DEFAULT_TOKEN_BUDGET,
        base_url: str = DEEPSEEK_BASE_URL,
        client: Any = None,
    ) -> None:
        if client is None:
            from openai import OpenAI  # noqa: PLC0415 — only needed when calling the API

            api_key = os.environ.get("DEEPSEEK_API_KEY")
            if not api_key:
                raise RuntimeError("DEEPSEEK_API_KEY is not set (see .env.example)")
            client = OpenAI(api_key=api_key, base_url=base_url, timeout=180, max_retries=4)
        self._client = client
        self._cache = cache
        self._budget = budget
        self._lock = threading.Lock()
        self.usage = Usage()

    def complete_json(self, request: Request) -> dict[str, Any]:
        """Return a cached JSON completion; retry once if the answer is not valid JSON."""
        cached = self._cache.get(request)
        if cached is not None:
            with self._lock:
                self.usage.cached_calls += 1
            return parse_json_object(cached)
        last_error: LlmError | None = None
        for _ in range(2):
            content, counts = self._call(request)
            try:
                parsed = parse_json_object(content)
            except LlmError as error:
                last_error = error
                continue
            self._cache.put(request, content, counts)
            return parsed
        assert last_error is not None
        raise last_error

    def _call(self, request: Request) -> tuple[str, dict[str, int]]:
        with self._lock:
            if self.usage.total_tokens >= self._budget:
                raise BudgetExceededError(
                    f"token budget spent: {self.usage.total_tokens} >= {self._budget}"
                )
        response = self._client.chat.completions.create(
            model=request.model,
            messages=[
                {"role": "system", "content": request.system},
                {"role": "user", "content": request.user},
            ],
            max_tokens=request.max_tokens,
            temperature=request.temperature,
            response_format={"type": "json_object"},
            extra_body={"thinking": {"type": "disabled"}},
        )
        choice = response.choices[0]
        content = choice.message.content or ""
        usage = response.usage
        counts = {
            "prompt_tokens": usage.prompt_tokens if usage else 0,
            "completion_tokens": usage.completion_tokens if usage else 0,
            "prompt_cache_hit_tokens": int(getattr(usage, "prompt_cache_hit_tokens", 0) or 0),
        }
        with self._lock:
            self.usage.calls += 1
            self.usage.prompt_tokens += counts["prompt_tokens"]
            self.usage.completion_tokens += counts["completion_tokens"]
            self.usage.prompt_cache_hit_tokens += counts["prompt_cache_hit_tokens"]
        if choice.finish_reason == "length":
            raise LlmError(f"answer truncated at max_tokens={request.max_tokens}")
        if not content.strip():
            raise LlmError("empty answer")
        return content, counts
